window.I18N_LANG = 'zh';

window.i18nT = function (key) {
  const d = window.I18N;
  return (d[window.I18N_LANG] && d[window.I18N_LANG][key]) ?? d.zh[key] ?? key;
};

// 模板令牌替换：@@key@@ -> 当前语言文案
window.i18nFill = function (html) {
  return String(html).replace(/@@([A-Za-z_][A-Za-z0-9_]*)@@/g, (_, k) => window.i18nT(k));
};

// 静态 HTML 翻译（设置窗口用）
window.i18nApply = function (root) {
  root = root || document;
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = window.i18nT(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = window.i18nT(el.dataset.i18nHtml); });
};
